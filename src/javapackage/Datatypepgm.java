package javapackage;

public class Datatypepgm {

	public static void main(String[] args) {
		byte bytenumber=10;
		System.out.println("value of bytenumber= "+bytenumber);
		
		short shortnumber=5;
		System.out.println("value of shortnumber= "+shortnumber);
		
		int intnumber=4;
		System.out.println("value of intnumber= "+intnumber);
		
		long longnumber=9876543210L;
		System.out.println("value of longnumber= "+longnumber);
		
		float floatnumber=3.14F;
		System.out.println("value of floatnumber= "+floatnumber);
		
		double doublenumber=45.85;
		System.out.println("value of doublenumber= "+doublenumber);
		
		boolean booleanvalue=5>8;
		System.out.println("result of booleanvalue= "+booleanvalue);
		
		char charactervalue='M'; //character values should be enclosed in single cords 
		System.out.println("result of charactervalue= "+charactervalue);
		
		//char datatype also accepts special characters
		char symbol='@';
		System.out.println("result of symbol= "+symbol);
		
		String stringvalue="Mathew";  // string value should be enclosed in double cords
		//*S in String should be always in uppercase as its a predefined class
		System.out.println("result of stringvalue= "+stringvalue);
		
		
	}

}
